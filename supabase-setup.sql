-- EL GAME: public score table for browser clients using the Supabase publishable key only.
create table if not exists public.scores (
  id bigint generated by default as identity primary key,
  game_id text not null check (game_id in ('snake', 'memory', 'clicker', 'pong')),
  player_name text not null check (char_length(btrim(player_name)) between 2 and 20),
  score integer not null check (score between 0 and 1000000000),
  created_at timestamptz not null default now(),
  constraint scores_game_player_unique unique (game_id, player_name)
);

-- Keep a player's best result when the browser upserts another score.
create or replace function public.keep_best_score()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.score := greatest(old.score, new.score);
  new.created_at := old.created_at;
  return new;
end;
$$;

drop trigger if exists scores_keep_best on public.scores;
create trigger scores_keep_best
before update on public.scores
for each row execute function public.keep_best_score();

alter table public.scores enable row level security;
grant select, insert, update on public.scores to anon, authenticated;
grant usage, select on sequence public.scores_id_seq to anon, authenticated;

drop policy if exists "Scores are publicly readable" on public.scores;
create policy "Scores are publicly readable"
on public.scores for select to anon, authenticated
using (true);

drop policy if exists "Visitors can submit scores" on public.scores;
create policy "Visitors can submit scores"
on public.scores for insert to anon, authenticated
with check (
  game_id in ('snake', 'memory', 'clicker', 'pong')
  and char_length(btrim(player_name)) between 2 and 20
  and score between 0 and 1000000000
);

drop policy if exists "Visitors can update scores" on public.scores;
create policy "Visitors can update scores"
on public.scores for update to anon, authenticated
using (true)
with check (
  game_id in ('snake', 'memory', 'clicker', 'pong')
  and char_length(btrim(player_name)) between 2 and 20
  and score between 0 and 1000000000
);
