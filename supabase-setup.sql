-- EL GAME: apply in Supabase SQL Editor.
-- Browsers can read scores but cannot write directly; only the Edge Function writes scores.
create table if not exists public.scores (
  id bigint generated by default as identity primary key,
  game_id text not null check (game_id in ('snake','memory','clicker','pong','breakout')),
  player_name text not null check (char_length(btrim(player_name)) between 2 and 20),
  score integer not null check (score between 1 and 1000000),
  player_id uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Upgrade older installations safely. Each anonymous account keeps one best score per game.
alter table public.scores add column if not exists player_id uuid;
alter table public.scores add column if not exists updated_at timestamptz not null default now();
alter table public.scores drop constraint if exists scores_game_player_unique;
-- Replace the former partial index: PostgREST upsert needs a regular unique index here.
drop index if exists public.scores_game_player_id_unique;
create unique index scores_game_player_id_unique on public.scores(game_id, player_id);

create or replace function public.keep_best_score()
returns trigger language plpgsql set search_path = '' as $$
begin
  if tg_op = 'UPDATE' then
    new.score := greatest(old.score, new.score);
    new.created_at := old.created_at;
  end if;
  new.updated_at := now();
  return new;
end;
$$;
drop trigger if exists scores_keep_best on public.scores;
create trigger scores_keep_best before insert or update on public.scores
for each row execute function public.keep_best_score();

alter table public.scores enable row level security;
revoke all on public.scores from anon, authenticated;
grant select on public.scores to anon, authenticated;
drop policy if exists "Scores are publicly readable" on public.scores;
create policy "Scores are publicly readable" on public.scores
for select to anon, authenticated using (true);
drop policy if exists "Visitors can submit scores" on public.scores;
drop policy if exists "Visitors can update scores" on public.scores;

